#!/usr/bin/env node
/**
 * Simulate guests tasting wines in a session.
 *
 * Usage:
 *   node scripts/sim-taste-wines.mjs <guests-json>
 *
 * Reads the JSON file produced by sim-join-session.mjs.
 * Each guest tastes wines in random order (free_order) with
 * realistic delays and varied ratings/notes.
 */

import fs from "node:fs";
import { createClient } from "@supabase/supabase-js";

// Load env
import path from "node:path";
const envPath = path.resolve(process.cwd(), ".env");
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const m = line.match(/^([^#=]+)=(.*)$/);
    if (m) process.env[m[1].trim()] = m[2].trim();
  }
}

const supabaseUrl = process.env.EXPO_PUBLIC_SUPABASE_URL;
const supabaseAnonKey = process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY;

const TASTING_NOTES = [
  "Fruktig med toner av körsbär",
  "Torr med bra syra",
  "Kryddig avslutning",
  "Mjuk och rund",
  "Elegant med lång eftersmak",
  "Lite för mycket tanniner",
  "Fräsch och blommig",
  "Mörka bär och choklad",
  "Mineralisk med citrus",
  "Fyllig med vanilj och ek",
  "Jordgubb och rabarber",
  "Honung och tropisk frukt",
  "Rökt och pepprig",
  "Lätt och enkel men trevlig",
  "Komplex med många lager",
];

const FOOD_PAIRINGS = [
  "Pasta", "Grillat kött", "Ost", "Fisk", "Skaldjur",
  "Lamm", "Vilt", "Pizza", "Sallad", "Dessert",
  "Charkuteri", "Kyckling", "Svamp", "Risotto", "Tapas",
];

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function pickN(arr, min, max) {
  const n = min + Math.floor(Math.random() * (max - min + 1));
  const shuffled = [...arr].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, n);
}

function randomRating() {
  // Weighted toward 3-4, realistic distribution
  const weights = [0.05, 0.15, 0.35, 0.30, 0.15]; // 1-5
  const r = Math.random();
  let cum = 0;
  for (let i = 0; i < weights.length; i++) {
    cum += weights[i];
    if (r <= cum) return i + 1;
  }
  return 3;
}

// ---

const guestsFile = process.argv[2];
if (!guestsFile || !fs.existsSync(guestsFile)) {
  console.error("Usage: node scripts/sim-taste-wines.mjs <guests-json>");
  console.error("       (generated by sim-join-session.mjs)");
  process.exit(1);
}

const guests = JSON.parse(fs.readFileSync(guestsFile, "utf8"));
if (!guests.length) {
  console.error("Inga gäster i filen.");
  process.exit(1);
}

const sessionId = guests[0].sessionId;

// Use a fresh client for each guest (authenticated as them)
function clientFor(guest) {
  const client = createClient(supabaseUrl, supabaseAnonKey);
  client.auth.setSession({
    access_token: guest.accessToken,
    refresh_token: guest.refreshToken,
  });
  return client;
}

// Fetch wines for the session
const adminClient = createClient(supabaseUrl, supabaseAnonKey);
await adminClient.auth.setSession({
  access_token: guests[0].accessToken,
  refresh_token: guests[0].refreshToken,
});

const { data: wines, error: winesError } = await adminClient
  .from("session_wines")
  .select("*")
  .eq("session_id", sessionId)
  .order("position", { ascending: true });

if (winesError || !wines?.length) {
  console.error("Kunde inte hämta viner:", winesError?.message || "inga viner i provningen");
  process.exit(1);
}

console.log(`\n🍷 Provning med ${wines.length} viner, ${guests.length} gäster`);
console.log(`   Viner: ${wines.map((w) => w.name).join(", ")}\n`);

// Each guest tastes wines in random order with delays
const guestPromises = guests.map(async (guest) => {
  const client = clientFor(guest);
  const wineOrder = [...wines].sort(() => Math.random() - 0.5);

  // Initial delay — guests don't all start at once
  const startDelay = 2000 + Math.random() * 5000;
  await sleep(startDelay);

  console.log(`  🥂 ${guest.name} börjar prova...`);

  for (let i = 0; i < wineOrder.length; i++) {
    const wine = wineOrder[i];
    const rating = randomRating();
    const notes = pick(TASTING_NOTES);
    const foodPairings = pickN(FOOD_PAIRINGS, 1, 3);

    const { error } = await client
      .from("session_tastings")
      .upsert(
        {
          session_id: sessionId,
          session_wine_id: wine.id,
          user_id: guest.userId,
          rating,
          notes,
          food_pairings: foodPairings,
        },
        { onConflict: "session_wine_id,user_id" },
      );

    if (error) {
      console.error(`    ✗ ${guest.name} – ${wine.name}: ${error.message}`);
    } else {
      const stars = "★".repeat(rating) + "☆".repeat(5 - rating);
      console.log(`    ${guest.name} → ${wine.name}: ${stars}  "${notes}"`);
    }

    // Wait 5-15 seconds between wines (simulates tasting + discussing)
    if (i < wineOrder.length - 1) {
      const delay = 5000 + Math.random() * 10000;
      await sleep(delay);
    }
  }

  console.log(`  ✅ ${guest.name} klar!`);
});

await Promise.all(guestPromises);

console.log(`\n🎉 Alla gäster har provsmakat alla viner!\n`);
